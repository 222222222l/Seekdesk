'use strict';
const assert=require('node:assert/strict');
const C=require('./core.js'), F=require('./fixture.js');
const frozen=F.rows.map(C.createRecord);
assert.deepEqual(frozen.map(r=>C.state(r).code),F.expected);
assert.deepEqual(frozen.slice(0,3).map(r=>r.track),['model','creator','manufacturing']);
assert.deepEqual(frozen[0].tags,['creator']);
assert.equal(frozen[0].requirements.find(q=>q.label==='最低年限').stated,false);
assert.equal(frozen[1].requirements.filter(q=>q.stated).length,2);
assert.equal(frozen[1].intake,'button_only');
assert.equal(frozen[2].requirements.find(q=>q.label==='制造业硬门槛').stated,false);
assert.equal(frozen[3].requirements.length,0);
assert.equal(frozen.filter(r=>C.state(r).bucket==='inactive').length,1);
assert.equal(C.state({...frozen[0],postedDate:'2026-10-20'}).bucket,'live');
assert.equal(C.state({...frozen[0],observations:[{state:'unverified',official:true,date:F.date,excerpt:'timeout'}]}).bucket,'watch');
assert.equal(C.state({...frozen[0],observations:[...frozen[0].observations,{state:'unverified',official:true,date:'2026-11-21',excerpt:'timeout'}]}).bucket,'watch');
const copied=C.createRecord({...F.rows[1],employer:'Another Company'});
assert.notEqual(copied.key,frozen[1].key);
assert.equal(C.conflicts(frozen,copied).length,1);
assert.equal(C.addRecord(frozen,copied).length,6);
assert.equal(C.addRecord(frozen,C.createRecord(F.rows[1])).length,5);
const link=C.createRecord({url:'https://example.com/job?id=15&utm_source=s#top'});
assert.equal(link.key,C.createRecord({url:'https://example.com/job?id=15'}).key);
assert.equal(C.state(link).code,'watch_description_missing');
assert.deepEqual(link.manual,[]);
assert.throws(()=>C.normalizeURL('javascript:alert(1)'));
assert.throws(()=>C.normalizeURL('https://127.1/'));
assert.throws(()=>C.normalizeURL('http://user:pass@example.com'));
assert.throws(()=>C.createRecord({...F.rows[0],requirements:[{label:'fake',match:'matched'}]}));
assert.throws(()=>C.logManual(link,'approved','manual check'));
assert.throws(()=>C.logManual(frozen[0],'platform_confirmed','manual check'));
assert.throws(()=>C.logManual(frozen[0],'resume_sent','manual check'));
let manual=C.logManual(frozen[0],'opened','Read page personally');
manual=C.logManual(manual,'approved','Reviewed personally');
manual=C.logManual(manual,'chat_started','Witnessed personally');
manual=C.logManual(manual,'resume_sent','Sent separately by hand');
manual=C.logManual(manual,'platform_confirmed','Separately saw platform receipt');
assert.equal(manual.manual.length,5);
assert.throws(()=>C.addRecord([manual],C.createRecord({...F.rows[0],roleID:'different'}),manual.key));
assert.equal(C.logManual(manual,'platform_confirmed','Separately saw platform receipt'),manual);
assert.throws(()=>C.simulate(frozen[0]));
assert.throws(()=>C.simulate({...frozen[3],fixture:true}));
const sim=C.simulate({...frozen[0],fixture:true});
assert.deepEqual(sim.simulation.map(x=>x.stage),['mock_send','mock_ack']);
assert.deepEqual(sim.manual,[]);
assert.equal(C.simulate(sim),sim);
for(const r of frozen.slice(0,3)){
 const d=C.draft(r,F.sampleProfile);
 assert(d.includes(C.tracks[r.track].name)&&d.includes('未发送')&&d.includes('虚构'));
}
console.log('PASS: five frozen states, three tracks, evidence gates, dedupe/conflicts, source state precedence, URL controls, manual receipts, fixture-only simulation');
